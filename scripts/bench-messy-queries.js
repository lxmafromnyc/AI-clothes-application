/* =========================================================
   Fynd — the messy-search benchmark's requests

   What scripts/bench-messy-live.js asks, and how each answer is judged.
   Version-controlled on its own so a result can always be traced to the
   exact request and the exact rule it was graded by.

   Every entry:
     id        stable; never reused or renumbered. M = messy, P = plain
     type      what makes it hard (see TYPES)
     set       'messy', or 'plain' — the control group, which must search
               exactly as it always did
     q         the request, as typed
     intent    what it means, in words, for a person reading the results

   and the rules it is graded by — patterns on the phrase Fynd asks the
   provider for, and on the titles of what comes back:
     target    the search must ask for one of these
     notAsked  the search must not ask for this: a garment it is only
               worn with or compared to, a thing ruled out, filler
     exclude   what the request rules out: the reading must record it,
               the search must not ask for it, no product shown may be it
     mayRule   other exclusions a careful reading may also record
     colours   colour families stated; any other colour is invented
     maxPrice / minPrice / gender / brands   stated, so they must be kept
     relevant  a title plainly what was asked (a list: all of them)
     strong    a relevant title that also says the rest of what was asked
     wrong     a title plainly not
     expectNone  nothing honest can be shown: zero products is right

   A title that does not say is counted neither way, so relevance and
   wrongness are both lower bounds.
   ========================================================= */

